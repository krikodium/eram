// Helper functions
export const getProductoById = (id) => {
  return mockProductos.find(producto => producto.id === parseInt(id));
};

export const getProductosByCategoria = (categoriaId, page = 1, limit = 20) => {
  const filtered = mockProductos.filter(producto => 
    producto.categoria_id === parseInt(categoriaId)
  );
  
  const startIndex = (page - 1) * limit;
  const endIndex = startIndex + limit;
  const productos = filtered.slice(startIndex, endIndex);
  
  return {
    productos,
    totalPages: Math.ceil(filtered.length / limit),
    currentPage: page,
    total: filtered.length,
    categoriaNombre: mockCategorias.find(cat => cat.id === parseInt(categoriaId))?.nombre || 'Categoría'
  };
};

export const getAllProductos = (page = 1, limit = 20) => {
  const startIndex = (page - 1) * limit;
  const endIndex = startIndex + limit;
  const productos = mockProductos.slice(startIndex, endIndex);
  
  return {
    productos,
    totalPages: Math.ceil(mockProductos.length / limit),
    currentPage: page,
    total: mockProductos.length
  };
};

